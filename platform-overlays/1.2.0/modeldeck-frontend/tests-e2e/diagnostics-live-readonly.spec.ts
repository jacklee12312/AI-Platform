import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
test.skip(process.env.MODELDECK_LIVE_READONLY!=='1','explicit read-only box verification')
test('live runtime baseline, immutable images, deployment history and recovery evidence',async({page,baseURL})=>{
 expect(baseURL).toBe('http://192.168.133.1:17780')
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));await page.setViewportSize({width:1440,height:1080})
 await page.goto('/diagnostics');await page.getByLabel('管理员密码').fill(process.env.MODELDECK_ADMIN_PASSWORD!)
 await page.getByRole('button',{name:'进入管理台'}).click();await page.getByRole('link',{name:'运行诊断',exact:true}).click()
 await expect(page.locator('[data-model="copaw-flash-9b"]')).toBeVisible({timeout:45000})
 const response=await page.request.get('/api/diagnostics');expect(response.ok()).toBe(true)
 const snapshot=await response.json();expect(snapshot.agent_available).toBe(true);expect(snapshot.current.inventory_available).toBe(true)
 const copaw=snapshot.current.parameters.find((i:{service:string})=>i.service==='copaw')
 await expect(page.locator('[data-model="copaw-flash-9b"]')).toContainText(String(copaw.actual_context))
 expect(copaw.source).toBe('service_props');expect(copaw.actual_slots).toBeGreaterThan(0)
 await expect(page.locator('[data-model="qwen3.8-27b"]')).toContainText('无当前上报值')
 await expect(page.locator('.diagnostic-container').filter({hasText:'gateway-admin-agent'})).toContainText('sha256:')
 await page.screenshot({path:'../../output/outputs/runtime-diagnostics-20260907/live-runtime.png'})
 await page.getByRole('tab',{name:'配置差异',exact:true}).click()
 await expect(page.locator('tr[data-setting]')).toHaveCount(snapshot.current.settings.length)
 await page.screenshot({path:'../../output/outputs/runtime-diagnostics-20260907/live-config.png'})
 await page.getByRole('tab',{name:'最近部署',exact:true}).click()
 await expect(page.locator('.diagnostic-content')).toContainText('首次观测')
 await page.getByRole('tab',{name:'故障与恢复',exact:true}).click()
 expect(snapshot.current.recoveries.length).toBeGreaterThan(0)
 await expect(page.locator('.diagnostic-content')).toContainText('20260904T133910-0e8028e3')
 await page.screenshot({path:'../../output/outputs/runtime-diagnostics-20260907/live-faults.png'})
 const downloading=page.waitForEvent('download');await page.getByRole('link',{name:'下载诊断快照'}).click()
 const exported=JSON.parse(await readFile((await (await downloading).path())!,'utf8'))
 expect(exported.current.containers.length).toBe(14);expect(exported.history.deployment.length).toBeGreaterThan(0)
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
 await page.screenshot({path:'../../output/outputs/runtime-diagnostics-20260907/live-mobile.png'})
 await page.setViewportSize({width:1440,height:1080});await page.getByRole('link',{name:'能力与示例',exact:true}).click();await expect(page.locator('.cap-card')).toHaveCount(24)
 await page.getByRole('link',{name:'批量任务',exact:true}).click();await expect(page.locator('tr[data-job-id]').filter({hasText:'验收 ASR WAV MP3 M4A'}).first()).toContainText('成功 3')
 await page.getByRole('link',{name:'Key 与用量',exact:true}).click();await expect(page.locator('main')).toContainText('网关资源控制')
 expect(errors).toEqual([])
})
