import { expect, test } from '@playwright/test'

test.skip(process.env.MODELDECK_LIVE_READONLY !== '1', 'explicit read-only box verification')
test('deployed batches show real OCR and audio results with downloadable archives', async ({ page, baseURL }) => {
  expect(baseURL).toBe('http://192.168.133.1:17780')
  const errors: string[] = []; page.on('pageerror', err => errors.push(err.message))
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.goto('/batches')
  await page.getByLabel('管理员密码').fill(process.env.MODELDECK_ADMIN_PASSWORD!)
  await page.getByRole('button', { name: '进入管理台' }).click()
  await page.getByRole('link', { name: '批量任务', exact: true }).click()
  await expect(page.locator('.cluster-state strong')).toHaveText('集群运行正常', { timeout: 30000 })
  const ocr = page.locator('tr[data-job-id]').filter({ hasText: '验收 OCR 图片与两页 PDF' }).first()
  await expect(ocr).toContainText('部分成功')
  await ocr.getByRole('button', { name: '详情', exact: true }).click()
  await expect(page.getByRole('region', { name: '任务详情' })).toContainText('已识别 2 / 2 页')
  await page.getByRole('button', { name: '查看文本' }).first().click()
  await expect(page.locator('.batch-preview pre')).toContainText('BATCH-20260907')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '../../output/outputs/batch-tasks-20260907/ui-live-batches.png' })
  await page.getByRole('region', { name: '任务详情' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '../../output/outputs/batch-tasks-20260907/ui-live-ocr.png' })
  const asr = page.locator('tr[data-job-id]').filter({ hasText: '验收 ASR WAV MP3 M4A' }).first()
  await expect(asr).toContainText('成功 3')
  await asr.getByRole('button', { name: '详情', exact: true }).click()
  await page.getByRole('button', { name: '查看文本' }).first().click()
  await expect(page.locator('.batch-preview pre')).not.toBeEmpty()
  await page.getByRole('region', { name: '任务详情' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '../../output/outputs/batch-tasks-20260907/ui-live-asr.png' })
  const downloading = page.waitForEvent('download')
  await asr.getByRole('link').click()
  expect((await downloading).suggestedFilename()).toMatch(/^batch-.*\.zip$/)
  expect(errors).toEqual([])
})
