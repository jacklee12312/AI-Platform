test('persistent deployment observations, fault evidence and safe JSON download',async({page})=>{
 await login(page);await page.getByRole('tab',{name:'最近部署',exact:true}).click()
 await expect(page.locator('.diagnostic-content')).toContainText('容器创建 · 首次观测')
 const rows=await page.locator('.diagnostic-content tbody tr').count();await page.reload()
 await page.getByRole('tab',{name:'最近部署',exact:true}).click();await expect(page.locator('.diagnostic-content tbody tr')).toHaveCount(rows)
 await page.getByRole('tab',{name:'故障与恢复',exact:true}).click()
 await expect(page.locator('.diagnostic-content')).toContainText('err_fatal')
 await expect(page.locator('.diagnostic-recoveries')).toContainText(['失败 · copaw',''])
 const downloading=page.waitForEvent('download');await page.getByRole('link',{name:'下载诊断快照'}).click()
 const download=await downloading;expect(download.suggestedFilename()).toBe('modeldeck-diagnostics.json')
 const text=await readFile((await download.path())!,'utf8');const exported=JSON.parse(text)
 expect(exported.history.deployment.length).toBeGreaterThan(0)
 expect(text).not.toContain('fixture-credential-must-never-be-exported')
 expect(text).not.toContain('UNKNOWN_SECRET')
})
