import { expect, test } from '@playwright/test'

test.skip(process.env.MODELDECK_INSTALL_FIXTURE !== '1', 'local simulated installer only')

test('select, preflight, download, install and activate without hidden submissions', async ({ page, baseURL }, info) => {
  expect(baseURL).toBe('http://127.0.0.1:18783')
  expect((await page.request.post('/__fixture/model-install/reset')).ok()).toBeTruthy()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/model-install')
  await page.getByLabel('管理员密码').fill('audit-test-password')
  await page.getByRole('button', { name: '进入管理台' }).click()
  await page.getByRole('link', { name: '模型安装', exact: true }).click()
  await expect(page.getByRole('heading', { name: '按需安装已适配模型' })).toBeVisible()
  await expect(page.locator('tbody tr')).toHaveCount(23)
  await page.getByLabel('选择 mobilenet_v2', { exact: true }).check()
  await page.getByLabel('安装后立即启用并自测（可能重启共享服务）').check()
  await page.getByRole('button', { name: '安装预检', exact: true }).click()
  await expect(page.locator('.install-actions')).toContainText('缺少运行镜像')
  await expect(page.getByRole('button', { name: '安装并启用', exact: true })).toBeDisabled()
  await page.getByLabel('选择 mobilenet_v2', { exact: true }).uncheck()
  await page.getByLabel('安装后立即启用并自测（可能重启共享服务）').uncheck()
  await page.getByLabel('按设备筛选').selectOption('CPU')
  await expect(page.locator('tbody tr')).toHaveCount(3)
  await page.getByLabel('选择 matcha-zh', { exact: true }).check()
  await expect(page.getByRole('button', { name: '安装但不启用', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '仅下载到缓存' }).click()
  await expect(page.locator('.operation-status')).toContainText('已完成')
  const row = page.getByRole('row').filter({ has: page.getByLabel('选择 matcha-zh', { exact: true }) })
  await expect(row).toContainText('已缓存 · 待安装')
  await page.getByRole('button', { name: '安装预检', exact: true }).click()
  await expect(page.locator('.install-actions')).toContainText('预检通过')
  await page.getByRole('button', { name: '安装但不启用', exact: true }).click()
  await expect(row).toContainText('已安装 · 未启用')
  await row.getByRole('button', { name: '启用自测' }).click()
  await expect(row).toContainText('已启用 · 查看运行诊断')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: info.outputPath('model-install-desktop.png'), fullPage: true })
  await row.getByRole('button', { name: '停用', exact: true }).click()
  await expect(row).toContainText('已安装 · 未启用')
  expect(errors).toEqual([])
})
