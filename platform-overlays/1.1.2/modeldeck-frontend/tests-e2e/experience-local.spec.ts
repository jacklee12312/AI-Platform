import { expect, test } from '@playwright/test'

test.skip(process.env.MODELDECK_EXPERIENCE_FIXTURE !== '1', 'explicit local simulated media only')
test.use({ trace: 'off', video: 'off' })

test('images, OCR, audio and original diagnostics stay paired without hidden inference', async ({ page, baseURL }, info) => {
  expect(baseURL).toBe('http://127.0.0.1:18785')
  const errors: string[] = [], writes: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/api/test/')) writes.push(request.url()) })
  await page.setViewportSize({ width: 1600, height: 1050 })
  await page.goto('/test')
  await page.getByLabel('管理员密码').fill('audit-test-password')
  await page.getByRole('button', { name: '进入管理台' }).click()
  await page.getByRole('link', { name: '模型体验', exact: true }).click()
  await page.getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.locator('.exp-success')).toHaveText('完成')
  await expect(page.locator('.chat-result')).toHaveText('1 2 3 4 5')
  const data = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 800; canvas.height = 400
    const ctx = canvas.getContext('2d')!; ctx.fillStyle = '#f2f5f2'; ctx.fillRect(0, 0, 800, 400)
    ctx.fillStyle = '#b9d4c4'; ctx.fillRect(80, 80, 400, 240); ctx.fillStyle = '#e7bc73'; ctx.fillRect(560, 40, 160, 120)
    ctx.fillStyle = '#15392c'; ctx.font = 'bold 50px sans-serif'; ctx.fillText('7  MODELDECK', 105, 220)
    return canvas.toDataURL('image/png').split(',')[1]!
  })
  const image = { name: 'modeldeck.png', mimeType: 'image/png', buffer: Buffer.from(data, 'base64') }
  await page.locator('[data-experience="cv"]').click()
  await expect(page.getByLabel('模型', { exact: true })).toHaveValue('yolov11_n')
  await page.getByLabel('检测图片').setInputFiles(image)
  await page.getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.locator('[data-detection-id]')).toHaveCount(2)
  const rect = page.locator('[data-detection-id="1"] rect')
  await expect(rect).toHaveAttribute('x', '80'); await expect(rect).toHaveAttribute('width', '400')
  await page.locator('[data-result-id="1"]').hover()
  await expect(page.locator('[data-detection-id="1"]')).toHaveClass(/active/)
  await page.getByLabel('检测结果显示阈值').fill('0.8')
  await expect(page.locator('[data-detection-id]')).toHaveCount(1)
  await page.getByLabel('显示检测框', { exact: true }).uncheck()
  await expect(page.locator('.image-stage svg')).toHaveCount(0)
  await page.getByLabel('显示检测框', { exact: true }).check()
  await page.screenshot({ path: info.outputPath('experience-detection.png'), fullPage: true })
  expect(writes).toHaveLength(2)
  await page.locator('[data-experience="ocr"]').click()
  await page.getByLabel('识别图片').setInputFiles(image)
  await page.getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.getByAltText('本次 OCR 原图')).toBeVisible()
  await expect(page.locator('.text-result pre')).toHaveText('7\nMODELDECK')
  await page.screenshot({ path: info.outputPath('experience-ocr.png'), fullPage: true })
  await page.getByLabel('识别图片').setInputFiles({ ...image, name: 'replacement.png' })
  await expect(page.locator('.text-result pre')).not.toHaveText('7\nMODELDECK')
  expect(writes).toHaveLength(3)
  await page.locator('[data-experience="asr"]').click()
  const audio = await (await page.request.get('/__fixture/experience/audio.wav')).body()
  await page.getByLabel('识别音频').setInputFiles({ name: 'sample.wav', mimeType: 'audio/wav', buffer: audio })
  await expect.poll(() => page.locator('audio').evaluate(el => (el as HTMLAudioElement).readyState)).toBeGreaterThanOrEqual(1)
  await page.getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.locator('.text-result pre')).toHaveText('本地测试转写。第二句话。')
  await page.getByRole('button', { name: '0:01.0–0:02.0 第二句话。' }).click()
  await expect.poll(() => page.locator('audio').evaluate(el => (el as HTMLAudioElement).currentTime)).toBeGreaterThanOrEqual(1)
  await page.locator('audio').evaluate(el => (el as HTMLAudioElement).pause())
  await page.screenshot({ path: info.outputPath('experience-asr.png'), fullPage: true })
  await page.locator('[data-experience="tts"]').click()
  await page.getByRole('button', { name: '生成语音', exact: true }).click()
  await expect(page.locator('audio[aria-label="合成音频播放器"]')).toBeVisible()
  await expect.poll(() => page.locator('audio').evaluate(el => (el as HTMLAudioElement).readyState)).toBeGreaterThanOrEqual(1)
  expect(await page.locator('audio').evaluate(el => (el as HTMLAudioElement).paused)).toBe(true)
  const download = page.waitForEvent('download'); await page.getByRole('link', { name: '下载 WAV' }).click()
  expect((await download).suggestedFilename()).toMatch(/\.wav$/)
  await page.screenshot({ path: info.outputPath('experience-tts.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath('experience-mobile.png'), fullPage: true })
  expect(writes).toHaveLength(5); expect(errors).toEqual([])
})

test('unavailable models, empty detections and mismatched geometry are not false successes', async ({ page }) => {
  await page.goto('/test')
  await page.getByLabel('管理员密码').fill('audit-test-password')
  await page.getByRole('button', { name: '进入管理台' }).click()
  await page.getByRole('link', { name: '模型体验', exact: true }).click()
  await expect(page.locator('option[value="qwen3.8-27b"]')).toHaveAttribute('disabled', '')
  await page.locator('[data-experience="cv"]').click()
  const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 80; c.height = 40; return c.toDataURL().split(',')[1]! })
  await page.getByLabel('检测图片').setInputFiles({ name: 'empty.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
  let raw = { ok: true, model: 'yolov11_n', original_size: [80, 40], result: { detections: [] as any[] } }
  await page.route('**/api/test/cv/**', route => route.fulfill({ json: raw }))
  await page.getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.getByText('本次阈值下未检出目标，不代表图片中一定没有目标。')).toBeVisible()
  raw = { ...raw, original_size: [40, 80], result: { detections: [{ box: [1, 1, 20, 20], score: .9 }] } }
  await page.getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.getByText('接口坐标尺寸与本次图片不一致，已隐藏框以避免错位。')).toBeVisible()
  await expect(page.locator('[data-detection-id]')).toHaveCount(0)
})
