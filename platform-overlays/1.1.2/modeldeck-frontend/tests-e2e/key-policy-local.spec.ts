import { expect, test } from '@playwright/test'

test.skip(process.env.MODELDECK_AUDIT_FIXTURE !== '1', 'local fixture only; never change customer keys')

test('create, edit and persist Key permissions and shared resource limits', async ({ page, baseURL }) => {
  expect(baseURL).toBe('http://127.0.0.1:18780')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('管理员密码').fill('audit-test-password')
  await page.getByRole('button', { name: '进入管理台' }).click()
  await page.getByRole('link', { name: 'Key 与用量' }).click()
  await expect(page.getByRole('heading', { name: 'Key 权限、资源与用量' })).toBeVisible()
  await page.getByRole('button', { name: '新建 API Key' }).click()
  const create = page.getByRole('dialog', { name: '新建 API Key' })
  const name = `LOCAL Key 权限验收 ${Date.now()}`
  await create.getByLabel('Key 名称').fill(name)
  await create.getByLabel('应用 / 部门归属').fill('测试应用')
  await create.getByLabel('到期时间', { exact: false }).fill('2030-12-31T23:59')
  await create.getByLabel('每分钟请求上限').fill('30')
  await create.getByLabel('Key 同时在途请求上限').fill('1')
  await create.getByLabel('每日推理请求额度').fill('12')
  await create.getByLabel('每月已知 Token 预警线').fill('100')
  await create.getByLabel('允许调用的模型').selectOption('selected')
  await create.getByRole('checkbox', { name: 'copaw-flash-9b', exact: false }).check()
  await page.screenshot({ path: '../../.codex-tmp/key-policy-create-desktop.png' })
  await create.getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'API Key 已创建' })).toBeVisible()
  await page.getByRole('button', { name: '我已安全保存' }).click()
  const row = page.locator('.key-table tbody tr').filter({ hasText: name })
  await expect(row).toContainText('已授权 1 个')
  await expect(row).toContainText('频率 30 / 分钟')
  const records = await (await page.request.get('/api/api-keys')).json()
  const saved = records.data.find((item: { name: string }) => item.name === name)
  expect(saved.policy).toMatchObject({ application: '测试应用', allowed_models: ['copaw-flash-9b'],
    rate_limit_per_minute: 30, max_concurrent_requests: 1, daily_request_limit: 12, monthly_token_warning: 100 })
  expect(saved.policy.expires_at).toBeTruthy()
  await row.getByRole('button', { name: '权限与限制' }).click()
  const edit = page.getByRole('dialog', { name: 'Key 权限与限制' })
  await expect(edit.getByLabel('每日推理请求额度')).toHaveValue('12')
  await edit.getByRole('button', { name: '清除到期时间' }).click()
  await edit.getByRole('checkbox', { name: 'copaw-flash-9b', exact: false }).uncheck()
  await expect(edit).toContainText('已选 0 个')
  await page.setViewportSize({ width: 390, height: 844 })
  const box = await edit.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(391)
  await page.screenshot({ path: '../../.codex-tmp/key-policy-mobile.png' })
  await edit.getByRole('button', { name: '保存权限与限制' }).click()
  await expect(row).toContainText('禁止全部模型')
  await expect(row).toContainText('永久有效')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: '配置并发上限' }).click()
  const resource = page.getByRole('dialog', { name: '配置并发上限' })
  await resource.getByLabel('网关总并发').fill('4')
  await resource.getByLabel('LQ50 设备组', { exact: true }).fill('2')
  await resource.getByLabel('copaw-flash-9b 并发上限', { exact: true }).fill('1')
  await page.screenshot({ path: '../../.codex-tmp/resource-policy-desktop.png' })
  await resource.getByRole('button', { name: '保存并发策略' }).click()
  await expect(page.getByText('并发策略已保存，对后续新请求生效。')).toBeVisible()
  await page.reload()
  await expect(row).toContainText('禁止全部模型')
  await expect(page.locator('.resource-summary')).toContainText('0 / 4')
  const fresh = (await (await page.request.get('/api/api-keys')).json()).data.find((item: { id: string }) => item.id === saved.id)
  expect(fresh.policy.allowed_models).toEqual([])
  expect(fresh.policy.expires_at).toBeNull()
  const policy = (await (await page.request.get('/api/resource-policy')).json()).policy
  expect(policy.global_max_concurrent).toBe(4)
  expect(policy.pool_limits.LQ50).toBe(2)
  expect(policy.model_limits['copaw-flash-9b']).toBe(1)
  const session = await (await page.request.get('/api/session')).json()
  await page.request.delete('/api/api-keys/' + saved.id, { headers: { 'X-CSRF-Token': session.csrf } })
  await page.reload()
  await expect(row).toHaveCount(0)
  await page.getByLabel('显示已撤销', { exact: false }).check()
  await expect(row).toContainText('已撤销')
  await page.getByLabel('显示已撤销', { exact: false }).uncheck()
  await page.screenshot({ path: '../../.codex-tmp/key-resource-overview.png' })
  expect(errors).toEqual([])
})

test('failed policy save keeps the dialog and draft for correction', async ({ page, baseURL }) => {
  expect(baseURL).toBe('http://127.0.0.1:18780')
  await page.goto('/')
  await page.getByLabel('管理员密码').fill('audit-test-password')
  await page.getByRole('button', { name: '进入管理台' }).click()
  await page.getByRole('link', { name: 'Key 与用量' }).click()
  const row = page.locator('.key-table tbody tr').filter({ hasText: 'LOCAL S08 示例客户' })
  await row.getByRole('button', { name: '权限与限制' }).click()
  const edit = page.getByRole('dialog', { name: 'Key 权限与限制' })
  await edit.getByLabel('每日推理请求额度').fill('99')
  await page.route('**/api/api-keys/*', route => route.fulfill({ status: 422, contentType: 'application/json',
    body: JSON.stringify({ detail: { detail: [{ loc: ['body', 'policy', 'daily_request_limit'], msg: '测试校验错误' }] } }) }))
  await edit.getByRole('button', { name: '保存权限与限制' }).click()
  await expect(edit.getByRole('alert')).toContainText('daily_request_limit：测试校验错误')
  await expect(edit.getByLabel('每日推理请求额度')).toHaveValue('99')
  await edit.getByRole('button', { name: '取消', exact: true }).click()
  await expect(row).toContainText('今日受理 0 / 不限')
})
