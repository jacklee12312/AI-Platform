import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.skip(process.env.MODELDECK_LIVE_READONLY !== '1', 'explicit read-only box verification')
test('deployed model links, unreported versions, LAN clipboard and downloadable contracts', async ({ page, baseURL }) => {
  expect(baseURL).toBe('http://192.168.133.1:17780')
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.goto('/models')
  await page.getByLabel('管理员密码').fill(process.env.MODELDECK_ADMIN_PASSWORD!)
  await page.getByRole('button', { name: '进入管理台' }).click()
  await page.getByRole('link', { name: '模型管理', exact: true }).click()
  const row = page.locator('tr').filter({ hasText: 'glm-ocr-0.9b' })
  await row.getByRole('link', { name: '能力说明与示例' }).click()
  await expect(page).toHaveURL(/capabilities\?model=glm-ocr-0.9b/)
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('网关未上报版本')
  await expect(dialog).toContainText('指定样例通过')
  await expect(dialog.getByLabel('可复制请求代码')).toHaveValue(/os.environ\["API_KEY"\]/)
  await dialog.getByLabel('示例语言').selectOption('powershell')
  await dialog.getByRole('button', { name: '复制请求', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText(/已复制|代码已选中/)
  const selection = await dialog.getByLabel('可复制请求代码').evaluate((el: HTMLTextAreaElement) => el.selectionEnd - el.selectionStart)
  expect(selection).toBeGreaterThan(500)
  await page.screenshot({ path: '../../output/outputs/model-capabilities-20260907/live-example.png' })
  await page.getByLabel('关闭能力说明').click()
  await expect(page.locator('.cap-card')).toHaveCount(24)
  await page.screenshot({ path: '../../output/outputs/model-capabilities-20260907/live-desktop.png', fullPage: true })
  await page.getByLabel('搜索模型能力').fill('qwen3.8')
  await expect(page.locator('.cap-card')).toContainText('当前模式未激活')
  await expect(page.locator('.cap-card')).toContainText('已知问题待闭环')
  const downloading = page.waitForEvent('download')
  await page.getByRole('link', { name: '下载接入说明' }).click()
  const download = await downloading
  const body = await readFile((await download.path())!, 'utf8')
  expect(body).toContain('版本未上报，历史验收适用性未确认')
  expect(body).toContain('```powershell')
  expect(body).toContain('```bash')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  expect(errors).toEqual([])
})
